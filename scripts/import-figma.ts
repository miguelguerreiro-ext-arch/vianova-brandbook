/** Offline deterministic transform: capture/variables.json -> tokens/src/*.tokens.json (DTCG).
 *  NO NETWORK. Re-running over an unchanged capture must produce no diff. */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { ROOT, readCapture, type Entry } from "./lib/capture.ts";

const DTCG_TYPE: Record<Entry["type"], string> = {
  COLOR: "color",
  FLOAT: "dimension",
  STRING: "fontFamily",
};
const FILE_FOR: Record<string, string> = {
  "Artefact / Primitive": "primitive",
  // 2026-10-13: "Paper" and "Data" were merged into one semantic colour tier, and the
  // status-pill roles were split out into their own collection.
  "Artefact / Colour": "colour",
  "Artefact / Status": "status",
  "Artefact / Brand gradient": "gradient",
  "Artefact / Geometry": "geometry",
  "Artefact / Type": "type",
  "Artefact / Font": "font",
};

const capture = readCapture();
mkdirSync(join(ROOT, "tokens/src"), { recursive: true });

let written = 0;
for (const [cname, coll] of Object.entries(capture.collections)) {
  const file = FILE_FOR[cname];
  if (!file) throw new Error(`capture has an unmapped collection: ${cname}`);

  const body: Record<string, unknown> = {};
  for (const [name, e] of Object.entries(coll.entries).sort((a, b) => a[0].localeCompare(b[0]))) {
    const vianova: Record<string, unknown> = { figma: cname, scopes: e.scopes };
    if (e.aliasOf) vianova["aliasOf"] = e.aliasOf;
    if (e.use) vianova["use"] = e.use;
    if (e.ladder) vianova["ladder"] = e.ladder;
    if (e.stop !== undefined) vianova["stop"] = e.stop;
    body[name] = {
      $value: e.unit && typeof e.value === "number" ? `${e.value}${e.unit}` : e.value,
      $type: DTCG_TYPE[e.type],
      $extensions: { vianova },
    };
  }

  writeFileSync(
    join(ROOT, `tokens/src/${file}.tokens.json`),
    JSON.stringify(
      {
        $description: `Generated by scripts/import-figma.ts from capture/variables.json — do not edit by hand. Source collection: ${cname} (mode ${coll.mode}).`,
        artefact: { [file]: body },
      },
      null,
      2,
    ) + "\n",
  );
  written++;
}
console.log(`import-figma: wrote ${written} DTCG files from ${capture.source.fileKey}`);
