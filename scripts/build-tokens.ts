/** tokens/src/*.tokens.json -> public/tokens.json + app/styles/paper.css */
import { writeFileSync, mkdirSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/capture.ts";

type Tok = { $value: string | number; $type: string; $extensions?: { vianova?: Record<string, unknown> } };

const srcDir = join(ROOT, "tokens/src");
const flat: Record<string, { value: string | number; type: string; group: string }> = {};

for (const f of readdirSync(srcDir).filter((f) => f.endsWith(".tokens.json")).sort()) {
  const doc = JSON.parse(readFileSync(join(srcDir, f), "utf8")) as { artefact: Record<string, Record<string, Tok>> };
  for (const [group, body] of Object.entries(doc.artefact)) {
    for (const [name, t] of Object.entries(body)) {
      flat[`${group}.${name}`] = { value: t.$value, type: t.$type, group };
    }
  }
}

mkdirSync(join(ROOT, "public"), { recursive: true });
writeFileSync(join(ROOT, "public/tokens.json"), JSON.stringify(flat, null, 2) + "\n");

const geo = (k: string) => String(flat[`geometry.${k}`]?.value ?? "");
const css = [
  "/* GENERATED by scripts/build-tokens.ts — do not edit by hand. */",
  ":root {",
  ...Object.entries(flat)
    .filter(([, t]) => t.group !== "font")
    .map(([k, t]) => `  --${k.replace(".", "-")}: ${t.value};`),
  "}",
  "",
  "@page {",
  "  size: A4;",
  `  margin: ${geo("margin")};`,
  "}",
  "",
  "/* HARD RULE from docs/design-brief.md: nothing within safe-edge of a page edge —",
  `   a typical office laser cannot print inside ~11.9pt. */`,
  ".artefact-page {",
  `  padding: ${geo("margin")};`,
  `  padding-left: ${geo("text-left")};`,
  "}",
  ".artefact-spine {",
  "  position: absolute; top: 0; height: 100%;",
  `  left: ${geo("spine-inset")};`,
  `  width: ${geo("spine-width")};`,
  "  background: linear-gradient(to bottom,",
  "    var(--gradient-stop-1) 0%, var(--gradient-stop-2) 24%, var(--gradient-stop-3) 48%,",
  "    var(--gradient-stop-4) 72%, var(--gradient-stop-5) 100%);",
  "}",
  "",
].join("\n");

mkdirSync(join(ROOT, "app/styles"), { recursive: true });
writeFileSync(join(ROOT, "app/styles/paper.css"), css);
console.log(`build-tokens: ${Object.keys(flat).length} tokens -> public/tokens.json, app/styles/paper.css`);
